import assert from 'node:assert/strict';
import {createGame,apply,tick,publicGame,sight,MAP,clear} from '../app/lib/mech.ts';
const now=100000,token='a'.repeat(48);const s=createGame(token,'Leader',now);
for(let i=1;i<8;i++)apply(s,String(i).repeat(48),{action:'join',name:'Pilot '+i},now);
assert.equal(s.players.length,8);
assert.throws(()=>apply(s,'9'.repeat(48),{action:'join'},now),/full/);
assert.throws(()=>apply(s,'1'.repeat(48),{action:'start'},now),/leader/);
apply(s,token,{action:'start'},now);assert.equal(s.wave,1);assert.equal(s.bots.length,21);
assert(!JSON.stringify(publicGame(s)).includes('"token"'));
const p=s.players[0];p.x=12.5;p.y=13.5;p.a=-Math.PI/2;s.bots=[{id:1,x:12.5,y:10.5,hp:70,heavy:false,fire:0}];
apply(s,token,{action:'sync',x:p.x,y:p.y,a:p.a,fire:true},now+500);assert.equal(s.bots[0].hp,35);
apply(s,token,{action:'sync',x:p.x,y:p.y,a:p.a,fire:true},now+510);assert.equal(s.bots[0].hp,35,'cooldown prevents duplicate shots');
apply(s,token,{action:'sync',x:p.x,y:p.y,a:p.a,fire:true},now+900);assert.equal(s.bots.length,0);assert.equal(p.kills,1);
tick(s,now+1000);assert.equal(s.phase,'intermission');tick(s,now+7200);assert.equal(s.wave,2);
const before={x:p.x,y:p.y};apply(s,token,{action:'sync',x:21,y:21},now+7400);assert(Math.hypot(p.x-before.x,p.y-before.y)<3.2,'teleport rejected');assert(clear(p.x,p.y));
assert.equal(sight({x:9,y:6},{x:12,y:6}),false,'scrap wall blocks fire');
s.bots=[];tick(s,now+7500);tick(s,now+14000);assert.equal(s.wave,3);s.bots=[];tick(s,now+14200);assert.equal(s.phase,'victory');
apply(s,token,{action:'start'},now+15000);p.hp=0;p.deadAt=now+15000;tick(s,now+21500);assert.equal(p.hp,100);assert(s.core<=575,'respawn costs core integrity');s.core=0;tick(s,now+22000);assert.equal(s.phase,'defeat');
console.log('PASS: 8-player capacity; ninth rejected; leader-only start; scaling; private tokens; shooting, cooldown and kills; cover; movement limits; three waves, victory, respawn and defeat.');
